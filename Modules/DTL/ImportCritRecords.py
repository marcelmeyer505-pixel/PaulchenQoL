import csv
import os
import re
from pathlib import Path
from tempfile import NamedTemporaryFile


DAMAGE_EVENTS = {"SWING_DAMAGE", "RANGE_DAMAGE", "SPELL_DAMAGE", "SPELL_PERIODIC_DAMAGE"}
PLAYER_GUID = re.compile(r"Player-[0-9]+-[0-9A-Fa-f]+\Z")
AFFILIATION_MINE = 0x1
ADVANCED_FIELDS = 19


def parse_hit(fields, advanced):
    event = fields[0]
    swing = event == "SWING_DAMAGE"
    suffix = fields[9 if swing else 12:]
    if not swing and suffix and suffix[-1] in {"ST", "AOE"}:
        suffix = suffix[:-1]

    # Forever can write the extended fields even when the header reports basic logging.
    if len(suffix) == ADVANCED_FIELDS + 10:
        suffix = suffix[ADVANCED_FIELDS:]
    elif advanced or len(suffix) not in (9, 10):
        return None
    if suffix[-3] != "1":
        return None

    guid = fields[1]
    if not PLAYER_GUID.fullmatch(guid):
        return None
    try:
        flags = int(fields[3], 16)
        damage = int(suffix[0])
        spell_id = 0 if swing else int(fields[9])
    except ValueError:
        return None
    if not (flags & AFFILIATION_MINE) or not 0 < damage < 2**63 or not 0 <= spell_id < 2**32:
        return None
    return guid, spell_id, damage, "Nahkampfangriff" if swing else fields[10], fields[2]


def parse_line(line, advanced):
    _, _, payload = line.partition("  ")
    event, _, remainder = payload.partition(",")
    if event == "COMBAT_LOG_VERSION":
        header = remainder.rstrip().split(",")
        if len(header) >= 3 and header[:2] == ["22", "ADVANCED_LOG_ENABLED"] and header[2] in {"0", "1"}:
            return header[2] == "1", None
        return None, None
    if advanced is None or event not in DAMAGE_EVENTS or not remainder.startswith("Player-"):
        return advanced, None
    try:
        fields = next(csv.reader([payload], strict=True))
    except csv.Error:
        return advanced, None
    return advanced, parse_hit(fields, advanced)


def game_directory(addon):
    return next((parent for parent in addon.parents if parent.name.lower() == "_forever_"), addon.parents[2])


def combat_logs(addon):
    return (game_directory(addon) / "Logs").glob("WoWCombatLog*.txt")


def read_records(log_paths):
    records = {}
    recognized_logs = 0
    for path in log_paths:
        advanced = None
        seen_header = False
        with path.open(encoding="utf-8-sig", errors="replace") as log:
            for line in log:
                if not line.endswith("\n"):
                    continue  # WoW may still be writing this event.
                advanced, hit = parse_line(line, advanced)
                seen_header = seen_header or advanced is not None
                if hit:
                    guid, spell_id, damage, name, _ = hit
                    character = records.setdefault(guid, {})
                    if spell_id not in character or damage > character[spell_id][0]:
                        character[spell_id] = damage, name
        recognized_logs += int(seen_header)
    return records, recognized_logs


def lua_string(value):
    return '"' + "".join(
        chr(byte) if 32 <= byte <= 126 and byte not in (34, 92) else f"\\{byte:03d}"
        for byte in value.encode("utf-8")
    ) + '"'


def write_records(destination, records):
    temporary = None
    try:
        with NamedTemporaryFile(mode="w", encoding="ascii", dir=destination.parent, delete=False) as output:
            temporary = Path(output.name)
            output.write("-- Generated by ImportCritRecords.py.\nlocal _, suite = ...\nlocal addon = suite.timeline\n"
                         "if not addon then return end\naddon.importedCritRecords = {\n")
            for guid, character in sorted(records.items()):
                output.write(f"    [{lua_string(guid)}] = {{\n")
                for spell_id, (damage, name) in sorted(character.items()):
                    output.write(f"        [{spell_id}] = {{ damage = {damage}, name = {lua_string(name)} }},\n")
                output.write("    },\n")
            output.write("}\n")
        os.replace(temporary, destination)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def main():
    addon = Path(__file__).resolve().parent
    logs = sorted(combat_logs(addon))
    if not logs:
        print("Kein Forever-Kampfprotokoll gefunden. Starte es mit /combatlog und beende einen Kampf.")
        return 1
    records, recognized_logs = read_records(logs)
    if not recognized_logs:
        print("Das vorhandene Kampfprotokoll hat ein unbekanntes Format.")
        return 1
    if not records:
        print("Noch keine eigenen kritischen Schadentreffer im Forever-Kampfprotokoll gefunden.")
        return 1
    write_records(addon / "CritRecordsData.lua", records)
    print(f"{sum(map(len, records.values()))} Crit-Rekorde importiert. Im Spiel /reload, dann /dtl crits.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except OSError as error:
        raise SystemExit(f"Import konnte nicht abgeschlossen werden. {error}") from None
