function app.GetLanguageSetting()
    local settings = type(PaulchenQoLSettings) == "table" and PaulchenQoLSettings
    local value = settings and settings.language
    return (value == "deDE" or value == "enUS") and value or "auto"
end

function app.GetLanguage()
    local setting = app.GetLanguageSetting()
    if setting == "deDE" or setting == "enUS" then return setting end
    return GetLocale and GetLocale() == "deDE" and "deDE" or "enUS"
end

function app.L(value)
    if type(value) ~= "string" or app.GetLanguage() ~= "enUS" then return value end
    return enUS[value] or value
end

function app.LF(template, ...)
    local localized = app.L(template)
    return localized:format(...)
end

-- Names returned by the game remain in the client's original language.
-- Only Paulchen-owned copy is translated when the user overrides the locale.
function app.LocalizeContext(value)
    return app.L(value)
end
